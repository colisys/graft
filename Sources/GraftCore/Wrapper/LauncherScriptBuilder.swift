import Foundation

/// Everything a generated launcher needs to boot the runtime on its own,
/// without Graft running.
public struct LauncherConfiguration: Sendable {
    public var tools: ToolLocations
    public var colimaStartArguments: [String]
    /// Full `docker` argument vector for first-time container creation
    /// (starts with `run`, includes `-d` and `--name`).
    public var containerRunArguments: [String]
    public var containerName: String
    public var display: String
    /// Final argv executed inside the container (already includes Electron
    /// flags and the `dbus-run-session --` wrapper).
    public var launchTokens: [String]
    public var processName: String
    public var xquartzAppPath: String?
    public var sessionDirectory: String
    public var logDirectory: String
    public var baseImage: BaseImage
    public var presetID: String?
    public var xrandrShimPath: String?
    public var maxRefreshRate: Int
    public var autoMaxRefreshRate: Bool

    public init(
        tools: ToolLocations,
        colimaStartArguments: [String],
        containerRunArguments: [String],
        containerName: String,
        display: String,
        launchTokens: [String],
        processName: String,
        xquartzAppPath: String?,
        sessionDirectory: String,
        logDirectory: String,
        baseImage: BaseImage = .ubuntu,
        presetID: String? = nil,
        xrandrShimPath: String? = nil,
        maxRefreshRate: Int = 0,
        autoMaxRefreshRate: Bool = false
    ) {
        self.tools = tools
        self.colimaStartArguments = colimaStartArguments
        self.containerRunArguments = containerRunArguments
        self.containerName = containerName
        self.display = display
        self.launchTokens = launchTokens
        self.processName = processName
        self.xquartzAppPath = xquartzAppPath
        self.sessionDirectory = sessionDirectory
        self.logDirectory = logDirectory
        self.baseImage = baseImage
        self.presetID = presetID
        self.xrandrShimPath = xrandrShimPath
        self.maxRefreshRate = max(0, maxRefreshRate)
        self.autoMaxRefreshRate = autoMaxRefreshRate
    }
}

/// Generates the `Contents/MacOS/launcher` shell script inside a wrapped app.
///
/// The launcher is deliberately a plain bash script: it survives OS updates,
/// needs no code signing of nested helpers, and is easy to audit. It wakes
/// XQuartz, boots Colima, ensures the container exists, starts the Linux
/// process, then stays alive while that process runs so the Dock icon is
/// meaningful.
public enum LauncherScriptBuilder {
    public static func build(
        entry: DesktopEntry,
        configuration: LauncherConfiguration,
        sessionID: String
    ) -> String {
        let quote = ShellQuote.quote
        let startArguments = ShellQuote.join(configuration.colimaStartArguments)
        let runArguments = ShellQuote.join(configuration.containerRunArguments)
        let launchArguments = ShellQuote.join(configuration.launchTokens)
        let shimPath = configuration.xrandrShimPath ?? ""
        let maxRefreshRate = max(0, configuration.maxRefreshRate)
        let autoMaxRefreshRate = configuration.autoMaxRefreshRate ? "1" : "0"
        // The container-side command records its own PID before replacing
        // itself with the app, so the host can kill it when the .app exits.
        let innerLaunch = "echo $$ > \"$GRAFT_PID_FILE\"; exec \(launchArguments)"
        let innerCleanup = "pid=$(cat \"$GRAFT_PID_FILE\" 2>/dev/null); if [ -n \"$pid\" ]; then kill \"$pid\" 2>/dev/null; /bin/sleep 0.3; kill -9 \"$pid\" 2>/dev/null; fi; rm -f \"$GRAFT_PID_FILE\""

        return """
        #!/bin/bash
        # Generated by Graft — regenerate from the Graft app instead of editing.
        # Desktop entry: \(entry.filePath)
        set -u

        NAME=\(quote(entry.name))
        DOCKER=\(quote(configuration.tools.docker ?? "/usr/local/bin/docker"))
        COLIMA=\(quote(configuration.tools.colima ?? "/usr/local/bin/colima"))
        XHOST=\(quote(configuration.tools.xhost ?? ""))
        XQUARTZ=\(quote(configuration.xquartzAppPath ?? ""))
        CONTAINER=\(quote(configuration.containerName))
        IMAGE=\(quote(configuration.baseImage.imageName))
        DISPLAY_HOST=\(quote(configuration.display))
        SESSION_DIR=\(quote(configuration.sessionDirectory))
        SESSION_ID=\(quote(sessionID))
        LOG_DIR=\(quote(configuration.logDirectory))
        APP_PID_FILE="/tmp/graft-session-\(sessionID)-$$.pid"
        ORIG_PPID=$PPID
        MAX_REFRESH=\(maxRefreshRate)
        AUTO_MAX_REFRESH=\(autoMaxRefreshRate)
        XRANDR_SHIM=\(quote(shimPath))
        XRANDR_SHIM_DEST=\(quote(XRandRShim.containerPath))
        PRELOAD_ENV=""

        mkdir -p "$LOG_DIR" "$SESSION_DIR"
        LOG_FILE="$LOG_DIR/$SESSION_ID.log"
        SESSION_FILE="$SESSION_DIR/$SESSION_ID.$$.session"
        exec >>"$LOG_FILE" 2>&1

        echo "==== [$(date '+%Y-%m-%d %H:%M:%S')] Graft launching $NAME ===="

        marker_written=0
        exec_pid=""
        cleanup() {
          [ "$marker_written" = "1" ] || return 0
          marker_written=0
          "$DOCKER" exec -u graft -e GRAFT_PID_FILE="$APP_PID_FILE" "$CONTAINER" sh -c \(quote(innerCleanup)) >/dev/null 2>&1 || true
          [ -n "$exec_pid" ] && kill "$exec_pid" 2>/dev/null || true
          rm -f "$SESSION_FILE"
        }
        trap cleanup EXIT INT TERM HUP

        # 1. XQuartz: allow local TCP connections and make sure it is running.
        if [ -n "$XQUARTZ" ]; then
          if ! /usr/bin/pgrep -x XQuartz >/dev/null 2>&1; then
            echo "Starting XQuartz..."
            /usr/bin/open -g -a "$XQUARTZ" || true
          fi
          for _ in $(/usr/bin/seq 1 60); do
            [ -S /tmp/.X11-unix/X0 ] && break
            /bin/sleep 0.5
          done
          if [ -n "$XHOST" ] && [ -x "$XHOST" ]; then
            DISPLAY=:0 "$XHOST" + 127.0.0.1 >/dev/null 2>&1 || true
          fi
        else
          echo "WARNING: XQuartz is not installed. Run: brew install --cask xquartz"
        fi

        # 2. Colima virtual machine.
        if ! "$COLIMA" status >/dev/null 2>&1; then
          echo "Starting Colima..."
          "$COLIMA" start \(startArguments) || { echo "ERROR: colima start failed"; exit 1; }
        fi

        # 3. Container.
        if "$DOCKER" inspect "$CONTAINER" >/dev/null 2>&1; then
          state=$("$DOCKER" inspect -f '{{.State.Running}}' "$CONTAINER" 2>/dev/null || echo false)
          if [ "$state" != "true" ]; then
            echo "Starting container $CONTAINER..."
            "$DOCKER" start "$CONTAINER" >/dev/null || { echo "ERROR: container start failed"; exit 1; }
          fi
        else
          if ! "$DOCKER" image inspect "$IMAGE" >/dev/null 2>&1; then
            echo "ERROR: base image $IMAGE is missing. Open Graft and start the runtime to rebuild it."
            /usr/bin/osascript -e 'display notification "缺少基础镜像，请打开 Graft 启动运行环境" with title "Graft"' >/dev/null 2>&1 || true
            exit 1
          fi
          echo "Creating container $CONTAINER (first run)..."
          "$DOCKER" \(runArguments) || { echo "ERROR: container creation failed"; exit 1; }
          state=false
        fi

        if [ "$state" != "true" ]; then
          for _ in $(/usr/bin/seq 1 90); do
            state=$("$DOCKER" inspect -f '{{.State.Running}}' "$CONTAINER" 2>/dev/null || echo false)
            [ "$state" = "true" ] && break
            /bin/sleep 1
          done
        fi

        [ "$state" = "true" ] || { echo "ERROR: container did not become ready: $CONTAINER"; exit 1; }

        # 3b. Present the macOS refresh rate to X11 clients. XQuartz rootless
        #     mode hard-codes a 1 Hz fake mode; the shim rewrites XRandR replies.
        if [ "$AUTO_MAX_REFRESH" = "1" ]; then
          MAX_REFRESH="${GRAFT_MAX_REFRESH:-$MAX_REFRESH}"
        fi
        if [ -n "$XRANDR_SHIM" ] && [ -f "$XRANDR_SHIM" ] && [ "$MAX_REFRESH" -gt 0 ] 2>/dev/null; then
          if "$DOCKER" cp "$XRANDR_SHIM" "$CONTAINER:$XRANDR_SHIM_DEST" >/dev/null 2>&1; then
            PRELOAD_ENV="-e LD_PRELOAD=$XRANDR_SHIM_DEST -e GRAFT_MAX_REFRESH=$MAX_REFRESH"
          else
            echo "WARNING: could not install XRandR refresh shim"
          fi
        fi

        # 4. Mark the session and run the app in the foreground so this .app
        #    stays alive exactly as long as the Linux process does.
        printf '%s\\t%s\\t%s\\t%s\\t%s\\n' "$$" "$(date +%s)" "$NAME" "$CONTAINER" "$APP_PID_FILE" > "$SESSION_FILE"
        marker_written=1

        echo "Launching inside container..."
        "$DOCKER" exec -u graft -e GRAFT_PID_FILE="$APP_PID_FILE" -e DISPLAY="$DISPLAY_HOST" -e HOME=/home/graft -e XDG_RUNTIME_DIR=/tmp/runtime-graft $PRELOAD_ENV "$CONTAINER" sh -c \(quote(innerLaunch)) &
        exec_pid=$!
        while kill -0 "$exec_pid" 2>/dev/null; do
          if [ "$PPID" != "$ORIG_PPID" ] || ! kill -0 "$ORIG_PPID" 2>/dev/null; then
            echo "Launcher parent exited; stopping the Linux application."
            cleanup
            exit 0
          fi
          /bin/sleep 1
        done
        wait "$exec_pid"
        status=$?
        if [ "$status" -ne 0 ]; then
          echo "WARNING: docker exec exited with code $status"
        fi
        case "$status" in
          125|126|127)
            /usr/bin/osascript -e 'display notification "Linux 应用未能启动，请查看 Graft 日志" with title "Graft"' >/dev/null 2>&1 || true
            ;;
        esac

        echo "Application exited."
        """
    }
}
